            | "localStorage"
            | "sessionStorage"
            | "fetch"
            | "process"
            | "Buffer"
            | "require"
            | "module"
            | "__dirname"
            | "__filename"
            | "setTimeout"
            | "setInterval"
            | "setImmediate"
            | "clearTimeout"
            | "clearInterval"
