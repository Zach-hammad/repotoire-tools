//! Authoritative TypeScript/JavaScript environment classification.
//!
//! Language built-ins are intrinsic names supplied by ECMAScript or
//! TypeScript and do not become graph nodes. Platform globals are supplied by
//! a host environment and remain visible as `External(AmbientGlobal)` nodes.

